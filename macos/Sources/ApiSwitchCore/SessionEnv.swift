import Foundation

public enum SessionEnv {
  public static let codexKeys = ["OPENAI_API_KEY", "OPENAI_BASE_URL", "CODEX_API_KEY"]

  public static func set(_ values: [String: String]) {
    for (key, value) in values {
      setenv(key, value, 1)
      _ = ProcessRunner.run("/bin/launchctl", ["setenv", key, value])
    }
    writeActiveEnv(values)
  }

  public static func unset(_ keys: [String]) {
    for key in keys {
      unsetenv(key)
      _ = ProcessRunner.run("/bin/launchctl", ["unsetenv", key])
    }
    writeActiveEnv([:])
  }

  private static func writeActiveEnv(_ values: [String: String]) {
    Paths.ensureDir(Paths.apiswitchDir)
    if values.isEmpty {
      try? FileManager.default.removeItem(atPath: Paths.activeEnv)
      return
    }
    var lines = ["# Generated by ApiSwitch — do not edit"]
    for key in values.keys.sorted() {
      let v = values[key] ?? ""
      let escaped = v.replacingOccurrences(of: "'", with: "'\"'\"'")
      lines.append("export \(key)='\(escaped)'")
    }
    Paths.atomicWrite(Paths.activeEnv, content: lines.joined(separator: "\n") + "\n")
  }
}

enum ProcessRunner {
  @discardableResult
  static func run(_ launchPath: String, _ args: [String]) -> Int32 {
    let task = Process()
    task.executableURL = URL(fileURLWithPath: launchPath)
    task.arguments = args
    task.standardOutput = FileHandle.nullDevice
    task.standardError = FileHandle.nullDevice
    do {
      try task.run()
      task.waitUntilExit()
      return task.terminationStatus
    } catch {
      return -1
    }
  }
}
